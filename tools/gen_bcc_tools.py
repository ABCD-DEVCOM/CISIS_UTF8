#!/usr/bin/env python3
"""Generates build_windows_tools_bcc55.bat from the .mak files (object lists of each utility).
Usage (from the repository root):  python3 tools/gen_bcc_tools.py crunchif crunchmf retag ifkeys i2id id2i > build_windows_tools_bcc55.bat"""
import re, sys
tools = sys.argv[1:] or ['crunchif', 'crunchmf', 'retag', 'ifkeys', 'i2id', 'id2i']
out = []
out.append('''@echo off
REM build_windows_tools_bcc55.bat - GENERATED by tools/gen_bcc_tools.py (do not edit by hand).
REM Builds the ABCD utilities with Borland C++ 5.5: %s
REM Same platform flags as the mx.exe of build_windows_bcc55.bat; the format flags (CIWTF/INCPROCX/...)
REM are the ones of the BIREME .mak files for these utilities.
REM *** NOT TESTED: it needs a Windows machine with BCC 5.5. ***
REM Usage: build_windows_tools_bcc55.bat [isis1660|ffi1660]      (default: isis1660)
REM (build_windows_all_bcc55.bat tools builds the same utilities for every variant)
setlocal
cd /d "%%~dp0"
if "%%BCC%%"=="" set BCC=C:\\Borland\\BCC55
if not exist "%%BCC%%\\Bin\\bcc32.exe" (
  echo bcc32.exe not found in %%BCC%%\\Bin. Set the BCC variable.
  exit /b 1
)
set PATH=%%BCC%%\\Bin;%%PATH%%
set VAR=%%1
if "%%VAR%%"=="" set VAR=isis1660
set FFI=1
if /i "%%VAR%%"=="isis1660" set FFI=0
if /i "%%VAR%%"=="isis1660" goto varok
if /i "%%VAR%%"=="ffi1660" goto varok
echo unknown variant: %%VAR%%   (valid: isis1660 ffi1660; use build_windows_all_bcc55.bat tools for the others)
exit /b 1
:varok
set OUT=dist\\windows32\\%%VAR%%
if not exist dist mkdir dist
if not exist dist\\windows32 mkdir dist\\windows32
if not exist %%OUT%% mkdir %%OUT%%
set PLAT=-DGCC=0 -DPC=1 -DDOS32BITS=1 -DMSC=0 -DUNIX=0 -DUTF8=1 -DINCLOADX=1 -DCIFFI=%%FFI%% -DLIND=0 -DLIND4=0 -DISISXL=1 -DISISXL512=0 -DWWWISIS=0 -D_FILE_OFFSET_BITS=0 -D_LARGEFILE64_SOURCE=0 -DPCREADLINUX=0
set FMT=-DCIWTF=0 -DINCPROCX=0 -DINCPRECX=0 -DEXCFMCGI=1 -DEXCFMXML=1
set OPT=-I"%%BCC%%\\Include" %%PLAT%% %%FMT%%
''' % ' '.join(tools))
for t in tools:
    mak = open(t + '.mak', 'rb').read().decode('latin-1').replace('\r\n', '\n')
    m = re.search(r'(?m)^\t\$\(CC\)\s+-o\s+%s\s+(.*?)\s*\$\(CCLIBS\)' % re.escape(t), mak)
    if not m: sys.exit('ERROR: link line of %s.mak not found' % t)
    objs = m.group(1).split()
    srcs = [o[:-2] + '.c' for o in objs if o.endswith('.o')]
    out.append('echo ===== %s =====' % t)
    out.append('bcc32 %%OPT%% -c %s' % ' '.join(srcs))
    out.append('if errorlevel 1 goto erro')
    out.append('bcc32 -L"%%BCC%%\\Lib" -e%%OUT%%\\%s.exe %s' % (t, ' '.join(o[:-2] + '.obj' for o in objs if o.endswith('.o'))))
    out.append('if errorlevel 1 goto erro')
    out.append('del *.obj')
    out.append('')
out.append('del *.tds 2>nul')
out.append('del %OUT%\\*.tds 2>nul')
out.append('echo.')
out.append('echo DONE: %OUT%')
out.append('exit /b 0')
out.append('')
out.append(':erro')
out.append('echo.')
out.append('echo *** FAILED (see the message above) ***')
out.append('exit /b 1')
sys.stdout.buffer.write(('\n'.join(out) + '\n').replace('\r\n','\n').replace('\n','\r\n').encode('latin-1'))

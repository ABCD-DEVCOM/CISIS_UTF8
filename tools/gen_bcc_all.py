#!/usr/bin/env python3
"""Generate build_windows_all_bcc55.bat: builds every Windows-capable variant of mx.exe / wxis.exe
(and, on request, the ABCD utilities) with Borland C++ 5.5, in one go.

Usage (from the repository root):
    python3 tools/gen_bcc_all.py > build_windows_all_bcc55.bat

The compile/link lists for mx and wxis are taken from build_windows_bcc55.bat (single source of truth);
the utilities' lists come from their .mak files, exactly like tools/gen_bcc_tools.py.
Only the 32-bit variants without large-file support exist on Windows: the "G" variants (64-bit file
offsets) need LSEEK64, which BCC 5.5 does not provide, so they are Linux-only. "bigisis" is built here
WITHOUT large-file support (like BIREME's own Windows bigisis, 5.7f, banner PC32/W/F/M/1048576/16/256/I),
so its files are limited to 2 GiB.
"""
import re, sys

TOOLS = sys.argv[1:] or ['crunchif', 'crunchmf', 'retag', 'ifkeys', 'i2id', 'id2i']

# ---- variant table (same names and meaning as build_linux.sh) --------------------------------
# name: (CIFFI, LIND, ISISXL, ISISXL512, SUPERISIS)
VARIANTS = [
    ('isis',     0, 0, 0, 0, 0),   # PC32/W/M/32767/10/30
    ('isis1660', 0, 0, 1, 0, 0),   # PC32/W/M/32767/16/60      (ABCD's administrative databases)
    ('lind',     0, 1, 1, 0, 0),   # L (inverted file with 32-bit postings), 16/60
    ('lind512',  0, 1, 1, 1, 0),   # L, 16/512
    ('ffi',      1, 1, 1, 0, 0),   # F/L, MFRL 1048576, 16/60
    ('ffi512',   1, 1, 1, 1, 0),   # F/L, MFRL 1048576, 16/512
    ('ffi1660',  1, 0, 1, 0, 0),   # F, MFRL 1048576, 16/60 (classic inverted file)
    ('bigisis',  1, 0, 1, 0, 1),   # F, MFRL 1048576, 16/256 (ABCD's large databases; files < 2 GiB here)
]


def section(lines, start_marker, end_marker):
    """lines between the first line containing start_marker (exclusive) and the first one containing end_marker (exclusive)"""
    a = next(i for i, l in enumerate(lines) if start_marker in l)
    b = next(i for i, l in enumerate(lines) if i > a and end_marker in l)
    return lines[a + 1:b]


src = open('build_windows_bcc55.bat', 'rb').read().decode('latin-1').replace('\r\n', '\n').split('\n')
mx_lines = section(src, 'echo ===== mx =====', 'del *.obj')
wx_lines = section(src, 'echo ===== wxis =====', 'del *.tds')
if not mx_lines or not wx_lines:
    sys.exit('ERROR: could not find the mx / wxis sections in build_windows_bcc55.bat')


def adapt(l):
    # the old script jumps to :erro; inside the :one subroutine we jump to :onefail
    return l.replace('goto erro', 'goto onefail')


out = []
w = out.append
w(r'''@echo off
REM build_windows_all_bcc55.bat - GENERATED by tools/gen_bcc_all.py (do not edit by hand).
REM Builds ALL Windows variants of mx.exe and wxis.exe with Borland C++ 5.5 (and optionally the ABCD utilities),
REM one folder per variant:  dist\windows32\<variant>[-ansi]\
REM
REM *** NOT TESTED: it needs a Windows machine with BCC 5.5. If something fails, keep the output and compare it
REM     with the official BIREME .bat files in CISIS_UNI_Win\projects. ***
REM
REM Usage:  build_windows_all_bcc55.bat [utf8|ansi|both] [tools] [variant ...]
REM    utf8 (default) | ansi | both    character set of the engine (ANSI = the classic BIREME behaviour)
REM    tools                           also build the ABCD utilities (%s)
REM    variant ...                     subset, e.g.  ffi1660 isis   (default: all of them)
REM
REM Variants (same names as build_linux.sh; banner = PC32/W/[F]/[L]/M/<max record>/<LE1>/<LE2>/I):
REM    isis      M/32767/10/30           record <= 32,767 bytes, keys 30      (original CDS/ISIS limits)
REM    isis1660  M/32767/16/60           record <= 32,767 bytes, keys 60
REM    lind      L/M/32767/16/60         + inverted file with 32-bit postings (.ly1/.ly2/.iyp)
REM    lind512   L/M/32767/16/512        keys up to 512 bytes
REM    ffi       F/L/M/1048576/16/60     records up to 1 MiB, LIND inverted file
REM    ffi512    F/L/M/1048576/16/512    records up to 1 MiB, keys up to 512
REM    ffi1660   F/M/1048576/16/60       records up to 1 MiB, classic inverted file
REM    bigisis   F/M/1048576/16/256      records up to 1 MiB, classic inverted file, keys up to 256 (ABCD's large databases)
REM The "G" variants (files > 2 GB) only exist on Linux (build_all.sh); bigisis here is limited to 2 GiB files.
REM The banner of every Windows build carries "PC32" instead of "G/PC" (compiled with Borland, not gcc).
REM See _docs/LIMITS.md for the exact limits of each variant.
setlocal EnableDelayedExpansion
set ROOT=%%~dp0
cd /d "!ROOT!"
if "%%BCC%%"=="" set BCC=C:\Borland\BCC55
if not exist "%%BCC%%\Bin\bcc32.exe" (
  echo bcc32.exe not found in %%BCC%%\Bin. Set the BCC variable or run find_compilers.ps1
  exit /b 1
)
set PATH=%%BCC%%\Bin;%%PATH%%

set MODE=utf8
set WITHTOOLS=0
set LIST=
:args
if "%%~1"=="" goto argsdone
if /i "%%~1"=="utf8"  (set MODE=utf8) else if /i "%%~1"=="ansi" (set MODE=ansi) else if /i "%%~1"=="both" (set MODE=both) else if /i "%%~1"=="tools" (set WITHTOOLS=1) else (set LIST=!LIST! %%~1)
shift
goto args
:argsdone
if "!LIST!"=="" set LIST=%s

if not exist dist mkdir dist
if not exist dist\windows32 mkdir dist\windows32
set FAILED=0
set RESULT=
for %%%%V in (!LIST!) do call :variant %%%%V
echo.
echo ======================= SUMMARY =======================
for %%%%R in (!RESULT!) do echo   %%%%R
echo.
if "!FAILED!"=="0" (echo ALL OK: dist\windows32\) else (echo *** SOME BUILDS FAILED ***)
exit /b !FAILED!

:variant
set VAR=%%1
set VFLAGS=
''' % (' '.join(TOOLS), ' '.join(v[0] for v in VARIANTS)))
for name, ciffi, lind, xl, xl512, sup in VARIANTS:
    w('if /i "%%VAR%%"=="%s" set VFLAGS=-DCIFFI=%d -DLIND=%d -DISISXL=%d -DISISXL512=%d -DSUPERISIS=%d' % (name, ciffi, lind, xl, xl512, sup))
w(r'''if "!VFLAGS!"=="" (
  echo unknown variant: %%VAR%%   ^(valid: %s^)
  set FAILED=1
  set RESULT=!RESULT! %%VAR%%:UNKNOWN
  goto :eof
)
if /i not "!MODE!"=="ansi" call :one %%VAR%% 1
if /i not "!MODE!"=="utf8" call :one %%VAR%% 0
goto :eof

REM ------------------------------------------------------------------------------------------------
REM :one <variant> <1=UTF-8 | 0=ANSI>
:one
set U=%%2
set OUT=dist\windows32\%%1
if "%%U%%"=="0" set OUT=dist\windows32\%%1-ansi
if not exist %%OUT%% mkdir %%OUT%%
echo.
echo ################ %%1  UTF8=%%U%%  ->  %%OUT%% ################
REM INCLOADX=1 makes CISIS read uctab=/actab= from the .par (needed for Russian, Greek, Hebrew...); on for UTF-8 only
set COMMON=-I"%%BCC%%\Include" -DUTF8=%%U%% -DINCLOADX=%%U%% !VFLAGS! -DLIND4=0 -DCIWTF=1 -DINCPROCX=1 -DINCPRECX=1
''' % ' '.join(v[0] for v in VARIANTS))
w('echo ===== mx =====')
for l in mx_lines:
    if l.strip(): w(adapt(l))
w('del *.obj')
w('')
w('echo ===== wxis =====')
for l in wx_lines:
    if l.strip(): w(adapt(l))
w('')
w('if not "%WITHTOOLS%"=="1" goto onedone')
w(r'''REM ---- ABCD utilities (platform flags = the ones of mx, format flags = the ones of the BIREME .mak files)
set PLAT=-DGCC=0 -DPC=1 -DDOS32BITS=1 -DMSC=0 -DUNIX=0 -DUTF8=%U% -DINCLOADX=%U% !VFLAGS! -DLIND4=0 -DWWWISIS=0 -D_FILE_OFFSET_BITS=0 -D_LARGEFILE64_SOURCE=0 -DPCREADLINUX=0
set FMT=-DCIWTF=0 -DINCPROCX=0 -DINCPRECX=0 -DEXCFMCGI=1 -DEXCFMXML=1
set OPT=-I"%BCC%\Include" %PLAT% %FMT%''')
for t in TOOLS:
    mak = open(t + '.mak', 'rb').read().decode('latin-1').replace('\r\n', '\n')
    m = re.search(r'(?m)^\t\$\(CC\)\s+-o\s+%s\s+(.*?)\s*\$\(CCLIBS\)' % re.escape(t), mak)
    if not m:
        sys.exit('ERROR: link line of %s.mak not found' % t)
    objs = [o for o in m.group(1).split() if o.endswith('.o')]
    w('echo ===== %s =====' % t)
    w('bcc32 %%OPT%% -c %s' % ' '.join(o[:-2] + '.c' for o in objs))
    w('if errorlevel 1 goto onefail')
    w('bcc32 -L"%%BCC%%\\Lib" -e%%OUT%%\\%s.exe %s' % (t, ' '.join(o[:-2] + '.obj' for o in objs)))
    w('if errorlevel 1 goto onefail')
    w('del *.obj')
w(r''':onedone
del *.tds 2>nul
del %OUT%\*.tds 2>nul
set RESULT=!RESULT! %1:u%U%:OK
%OUT%\mx.exe 2>&1 | findstr /b /c:"XCore" /c:"CISIS"
goto :eof

:onefail
cd /d "!ROOT!"
del *.obj 2>nul
del wxis_src\*.obj 2>nul
echo.
echo *** FAILED: %1 (UTF8=%U%) - see the message above ***
set FAILED=1
set RESULT=!RESULT! %1:u%U%:FAILED
goto :eof''')
sys.stdout.buffer.write(('\n'.join(out) + '\n').replace('\r\n', '\n').replace('\n', '\r\n').encode('latin-1'))
